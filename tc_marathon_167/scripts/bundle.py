#!/usr/bin/env python3
"""Bundle the modular solver into the single source file Topcoder accepts.

    python3 scripts/bundle.py            # writes dist/WordGame.cpp and dist/WordGame.zip
    python3 scripts/bundle.py --check    # also compiles the bundle and the modular build
                                         # and checks they answer one game identically

src/WordGame.cpp is a unity translation unit; this script inlines every local
#include "..." it reaches, depth first, each file once. Include guards stay in
place, so the result is the same translation unit the compiler sees for
build/WordGame. System headers are left as they are.
"""
import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
LOCAL = re.compile(r'^\s*#\s*include\s+"([^"]+)"\s*$')


def inline(path, seen, out):
    path = path.resolve()
    if path in seen:
        return
    seen.add(path)
    out.append("// ---- %s ----\n" % path.relative_to(ROOT))
    for line in path.read_text().splitlines(keepends=True):
        m = LOCAL.match(line)
        if m:
            inline(path.parent / m.group(1), seen, out)
        else:
            out.append(line)
    if out and not out[-1].endswith("\n"):
        out.append("\n")


def bundle():
    out = ["// MM167 WordGame - single-file bundle generated by scripts/bundle.py from src/.\n"]
    inline(SRC / "WordGame.cpp", set(), out)
    return "".join(out)


def check(cpp):
    """Compile the bundle and play one tiny game against both binaries."""
    sys.path.insert(0, str(ROOT / "tests"))
    import selfplay
    with tempfile.TemporaryDirectory() as tmp:
        exe = Path(tmp) / "WordGame"
        subprocess.run(["c++", "-std=c++17", "-O2", "-o", str(exe), str(cpp)], check=True)
        modular = ROOT / "build" / "WordGame"
        if not modular.exists():
            raise SystemExit("build/WordGame missing: run make build first")
        if not selfplay.DICTIONARY.exists():
            print("bundle compiles; tools/enable2k.txt missing, skipped the game check")
            return
        game = (10, 7, 3, 2, 0.30, 99, [])
        a = selfplay.run_game(exe, *game)
        b = selfplay.run_game(modular, *game)
        if a != b:
            raise SystemExit("bundle and modular build disagree")
        print("bundle compiles and matches build/WordGame on a test game (%d actions)" % len(a))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", type=Path, default=ROOT / "dist")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    cpp = args.out / "WordGame.cpp"
    cpp.write_text(bundle())
    archive = args.out / "WordGame.zip"
    with ZipFile(archive, "w", ZIP_DEFLATED) as z:
        z.write(cpp, "WordGame.cpp")
    with ZipFile(archive) as z:
        assert z.namelist() == ["WordGame.cpp"]
    print(cpp, "and", archive)
    if args.check:
        check(cpp)


if __name__ == "__main__":
    main()
