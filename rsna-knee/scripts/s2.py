"""S2: pinned evaluation configs for the author's checkpoints and the S2 acceptance report.

  python scripts/s2.py configs                      # experiments/S2-*/config.json
  python scripts/s2.py report <pulled_dir> <exp_dir> --gpu-hours H [--kernel-version V]
"""

import argparse
import hashlib
import json
import shutil
import sys
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from rsna_knee import evaluation  # noqa: E402
from rsna_knee.reader.knee import LABELS  # noqa: E402

S1 = ROOT / "experiments" / "S1"
LABELS_CSV = S1 / "labels" / "labels_v0.csv"
CKPT_DIR = ROOT / "models" / "convnext_reader"
KAGGLE_REFERENCE = ROOT / "runs" / "baseline_0944" / "kaggle_v1" / "_own.csv"
TEST_TOLERANCE = 0.003
FOLD_GAP = 0.03
AUTHOR_OOF, OOF_TOLERANCE = 0.888, 0.015
HIDDEN_STUDIES, SAFETY = 1300, 1.5
OUTPUTS = ["preds_oof.csv", "preds_gold.csv", "preds_test.csv", "preds_gold_dicom.csv", "preds_test_dicom.csv",
           "logits.csv", "metrics.json", "timing.json", "run.json"]


def base_config():
    freeze = json.loads((S1 / "artifact_freeze.json").read_text())
    labels_sha = freeze["files"]["labels/labels_v0.csv"]
    if evaluation.sha256(LABELS_CSV) != labels_sha:
        raise ValueError("Local labels_v0.csv differs from the S1 freeze")
    ckpts = [{"file": f"cnxt_v0_fold{k}.pt", "fold": k, "sha256": evaluation.sha256(CKPT_DIR / f"cnxt_v0_fold{k}.pt")}
             for k in range(3)]
    return {"ckpts": ckpts, "infer": {"k_eval": 12, "res": None, "amp": "fp16", "batch_size": 4,
                                      "ensemble": "prob"},
            "sets": ["cross", "gold", "test"], "dicom": ["gold", "test"], "labels_sha256": labels_sha,
            "meta_sha256": evaluation.meta_digest(pd.read_csv(S1 / "cache384_train_meta.csv"))}


def write_configs():
    for name, extra in [("S2-smoke", {"limit": 16}), ("S2-E-base", {})]:
        config = {"name": name, **base_config(), **extra}
        evaluation.validate_config(config)
        path = ROOT / "experiments" / name / "config.json"
        path.parent.mkdir(parents=True, exist_ok=True)
        evaluation.write_json(path, config)
        print(path)


def labels_with_sha(digest):
    for path in [LABELS_CSV, *sorted((S1 / "labels" / "attempts").glob("*/labels_v0.csv"))]:
        if evaluation.sha256(path) == digest:
            return path
    raise FileNotFoundError(f"No archived labels_v0.csv has SHA256 {digest}")


# Fold tables generated by the same make_labels v0 algorithm in different environments.
FOLD_CANDIDATES = {
    "kaggle_v2_sklearn_1.6.1_x86 (S1 frozen, superseded)": S1 / "labels" / "attempts" / "v2" / "labels_v0.csv",
    "stable_rule (kaggle v3 = local, frozen)": LABELS_CSV,
    "local_sklearn_1.6.1_arm (gitignored run)": ROOT / "runs" / "s1-labels-pinned" / "labels_v0.csv",
}
# The author's notebook figure: held-out folds 0-2 (2,610 studies) and Gold58, by finding.
AUTHOR_WEAK = {"Baker's": 0.927, "Contusion": 0.884, "Medial OA": 0.891, "ACL": 0.903, "Medial Meniscus": 0.933,
               "MCL": 0.828, "Fracture": 0.918, "Lateral Meniscus": 0.884, "Effusion": 0.875, "Lateral OA": 0.864,
               "PF OA": 0.853, "Synovitis": 0.900}
AUTHOR_GOLD = {"Baker's": 0.976, "Contusion": 0.966, "Medial OA": 0.966, "ACL": 0.965, "Medial Meniscus": 0.963,
               "MCL": 0.946, "Fracture": 0.911, "Lateral Meniscus": 0.889, "Effusion": 0.880, "Lateral OA": 0.865,
               "PF OA": 0.843, "Synovitis": 0.761}


def fold_candidates(logits):
    """Which fold table the author's checkpoints were trained with, judged by their own losses."""
    base = pd.read_csv(LABELS_CSV, index_col=0)
    out = {}
    for name, path in FOLD_CANDIDATES.items():
        if not path.exists():
            continue
        folds = pd.read_csv(path, index_col=0).fold
        check = evaluation.fold_check(logits, base.assign(fold=folds.reindex(base.index)))
        out[name] = {"fold_column_sha256": hashlib.sha256(folds.to_csv().encode()).hexdigest(),
                     "changed_vs_frozen": int((folds.reindex(base.index) != base.fold).sum()),
                     "held_out_auc": {k: v["held_out_auc"] for k, v in check["held_out_vs_trained"].items()},
                     "gap": {k: v["gap"] for k, v in check["held_out_vs_trained"].items()},
                     "membership": {k: v["held_out_ckpt_has_highest_loss"] for k, v in check["membership"].items()}}
    return out


def author_comparison(m_oof, m_gold):
    weak = {k: m_oof["per_label"][k] - v for k, v in AUTHOR_WEAK.items()}
    gold = {k: m_gold["per_label"][k] - v for k, v in AUTHOR_GOLD.items()}
    return {"source": "notebooks/baseline_0944 figure, panel 3 (3-decimal values)",
            "oof_max_abs_diff": max(map(abs, weak.values())), "gold_max_abs_diff": max(map(abs, gold.values())),
            "oof_diff": weak, "gold_diff": gold}


def max_diff(a, b):
    a, b = pd.read_csv(a, index_col=0), pd.read_csv(b, index_col=0)
    if not a.index.sort_values().equals(b.index.sort_values()):
        raise ValueError("Prediction files cover different studies")
    return float((a.loc[b.index, LABELS] - b[LABELS]).abs().to_numpy().max())


def report(pulled, exp, gpu_hours, kernel_version):
    pulled, exp = Path(pulled), Path(exp)
    found = {p.name: p for p in pulled.rglob("*") if p.name in OUTPUTS}
    missing = set(OUTPUTS) - set(found)
    if missing:
        raise FileNotFoundError(f"Missing outputs: {sorted(missing)}")
    for name, path in found.items():
        shutil.copy2(path, exp / ("eval_metrics.json" if name == "metrics.json" else name))
    config = json.loads((exp / "config.json").read_text())
    run = json.loads((exp / "run.json").read_text())
    if run["config"]["ckpts"] != config["ckpts"] or run["config"]["sets"] != config["sets"]:
        raise ValueError("The pulled run used a different configuration")
    kernel = json.loads((exp / "eval_metrics.json").read_text())
    timing = json.loads((exp / "timing.json").read_text())

    # The kernel's summary must follow from the raw logits under the labels the run used.
    logits = pd.read_csv(exp / "logits.csv")
    run_labels = pd.read_csv(labels_with_sha(run["inputs"]["labels_sha256"]), index_col=0)
    run_oof = evaluation.oof_predictions(logits, run_labels)
    pulled_oof = pd.read_csv(exp / "preds_oof.csv", index_col=0)
    if not np.allclose(run_oof[LABELS].to_numpy(), pulled_oof.loc[run_oof.index, LABELS].to_numpy(), atol=1e-7):
        raise ValueError("preds_oof.csv does not follow from logits.csv")
    if abs(evaluation.macro_auc(evaluation.targets(run_labels, run_oof.index, "weak"), run_oof[LABELS].to_numpy())
           - kernel["oof"]["auc"]) > 1e-9:
        raise ValueError("Local OOF AUC differs from the kernel's summary")

    # Record metrics under the frozen table. Logits cover every weak study and checkpoint,
    # so a fold-table correction only changes which rows form the OOF set.
    labels = pd.read_csv(LABELS_CSV, index_col=0)
    if not labels.drop(columns="fold").equals(run_labels.drop(columns="fold").loc[labels.index]):
        raise ValueError("The frozen table differs from the run's labels beyond the fold column")
    oof = evaluation.oof_predictions(logits, labels)
    oof.to_csv(exp / "preds_oof.csv", float_format="%.9g")
    m_oof = evaluation.auc_summary(labels, oof, "weak", 2000)
    m_gold = evaluation.auc_summary(labels, pd.read_csv(exp / "preds_gold.csv", index_col=0), "gold", 2000)
    if abs(m_gold["auc"] - kernel["gold"]["auc"]) > 1e-9:
        raise ValueError("Local Gold58 AUC differs from the kernel's summary")
    fold = evaluation.fold_check(logits, labels)
    candidates = fold_candidates(logits)
    published = author_comparison(m_oof, m_gold)

    test_cache = max_diff(exp / "preds_test.csv", KAGGLE_REFERENCE)
    test_dicom = max_diff(exp / "preds_test_dicom.csv", KAGGLE_REFERENCE)
    held = fold["held_out_vs_trained"]
    fold_ok = {k: v["gap"] >= FOLD_GAP and abs(v["held_out_auc"] - AUTHOR_OOF) <= OOF_TOLERANCE
               for k, v in held.items()}
    dicom = timing["gold_dicom"]
    hidden = {"sample": "gold_dicom", "studies": dicom["studies"], "checkpoints": dicom["checkpoints"],
              "seconds_per_study_two_gpus": dicom["seconds_per_study_parallel"],
              "seconds_per_study_one_gpu": dicom["seconds_per_study_one_gpu"],
              "estimate_hours": HIDDEN_STUDIES * SAFETY * dicom["seconds_per_study_parallel"] / 3600,
              "formula": f"{HIDDEN_STUDIES} x {SAFETY} x seconds_per_study (2 GPUs, DICOM path, all checkpoints)"}
    gates = {
        "test_matches_kaggle_v1": {"passed": max(test_cache, test_dicom) <= TEST_TOLERANCE, "tolerance": TEST_TOLERANCE,
                                   "cache_max_abs_diff": test_cache, "dicom_max_abs_diff": test_dicom},
        "fold_consistency": {"passed": all(fold_ok.values()), "per_ckpt": fold_ok, "min_gap": FOLD_GAP,
                             "held_out_range": [AUTHOR_OOF - OOF_TOLERANCE, AUTHOR_OOF + OOF_TOLERANCE]},
        "m_gold_recorded": {"passed": m_gold["ci"] is not None, "auc": m_gold["auc"], "ci": m_gold["ci"]},
        "timing_recorded": {"passed": all(timing[t]["seconds_per_study_parallel"] for t in ("weak", "gold_dicom")),
                            "hidden_test_estimate": hidden},
        "cache_288_parity": {"passed": None, "note": "not applicable: S1 selected 384px NPY"},
    }
    verification = {"labels_sha256": evaluation.sha256(LABELS_CSV), "run_labels_sha256": run["inputs"]["labels_sha256"],
                    "m_oof": m_oof, "m_gold": m_gold, "m_gold_dicom": kernel.get("gold_dicom"),
                    "fold_check": fold, "fold_candidates": candidates, "author_published": published,
                    "dicom_parity": kernel["dicom_parity"], "gates": gates,
                    "environment": run["environment"], "inputs": run["inputs"],
                    "kernel_total_seconds": run["total_seconds"]}
    evaluation.write_json(exp / "verification.json", verification)
    passed = all(g["passed"] is not False for g in gates.values())
    fold_text = "折一致" if gates["fold_consistency"]["passed"] else "折不一致，M_oof 改用 S4 自训折"
    if verification["labels_sha256"] != verification["run_labels_sha256"]:
        fold_text = "S1 v2 折与作者不一致，改用稳定排序折（标签 kernel v3）后" + fold_text
    conclusion = (f"{'通过' if passed else '未全部通过'}：test 与 Kaggle v1 最大差 {max(test_cache, test_dicom):.2e}；"
                  f"{fold_text}（留出 AUC " + "/".join(f"{held[k]['held_out_auc']:.3f}" for k in sorted(held))
                  + "，与训练折差 " + "/".join(f"{held[k]['gap']:.3f}" for k in sorted(held))
                  + f"；作者公布的逐项 OOF 最大差 {published['oof_max_abs_diff']:.4f}）；"
                  f"DICOM 路径 {dicom['seconds_per_study_parallel']:.2f}s/study，隐藏集估计 {hidden['estimate_hours']:.2f}h")
    record = {"id": exp.name, "date": date.today().isoformat(),
              "config_diff": "作者 fold 0–2 检查点、作者推理配置（k_eval 12、res 256、fp16、概率平均）；读 S1 缓存",
              "kernel": "wangshu/rsna-knee-eval", "kernel_version": kernel_version,
              "m_oof": {"auc": m_oof["auc"], "ci": m_oof["ci"]}, "m_gold": {"auc": m_gold["auc"], "ci": m_gold["ci"]},
              "public_score": None, "gpu_hours": gpu_hours, "conclusion": conclusion}
    evaluation.write_json(exp / "metrics.json", record)
    print(json.dumps({"gates": gates, "conclusion": conclusion}, indent=2, ensure_ascii=False))
    return passed


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="command", required=True)
    sub.add_parser("configs")
    rep = sub.add_parser("report")
    rep.add_argument("pulled", type=Path)
    rep.add_argument("exp", type=Path)
    rep.add_argument("--gpu-hours", type=float, required=True)
    rep.add_argument("--kernel-version", type=int, required=True)
    args = ap.parse_args()
    if args.command == "configs":
        write_configs()
    else:
        report(args.pulled, args.exp, args.gpu_hours, args.kernel_version)


if __name__ == "__main__":
    main()
